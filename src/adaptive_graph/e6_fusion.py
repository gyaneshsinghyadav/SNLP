"""E6-C: leakage-safe, fully trainable structural/temporal fusion decoder.

The encoder and decoder are trained end-to-end; a prequential, history-trained
logistic-regression logit is a residual anchor, never fitted on test labels.
This is TGAT-inspired one-hop temporal attention, not HGTLP/SEAL reproduction.
"""
from __future__ import annotations

import torch
from torch import nn
import torch.nn.functional as F

from .e6_structural import FEATURE_NAMES
from .tgat import TemporalAttentionLinkPredictor


def reset_linear(module: nn.Module):
    if isinstance(module, nn.Linear):
        nn.init.xavier_uniform_(module.weight)
        nn.init.zeros_(module.bias)


class ResidualMLP(nn.Module):
    def __init__(self, in_dim: int, hidden: int, dropout: float):
        super().__init__()
        self.in_proj = nn.Linear(in_dim, hidden)
        self.in_norm = nn.LayerNorm(hidden)
        self.blocks = nn.ModuleList([
            nn.Sequential(nn.Linear(hidden, hidden), nn.GELU(), nn.Dropout(dropout),
                          nn.Linear(hidden, hidden)) for _ in range(2)
        ])
        self.norms = nn.ModuleList([nn.LayerNorm(hidden) for _ in range(2)])
        self.dropout = dropout

    def forward(self, x):
        x = self.in_norm(F.gelu(self.in_proj(x)))
        for block, norm in zip(self.blocks, self.norms):
            x = norm(x + F.dropout(block(x), self.dropout, training=self.training))
        return x


class FullStructuralTemporalFusion(nn.Module):
    """Gated dual encoder with learned feature interactions and residual LR anchor.

    Symmetry: the temporal states from ``TemporalAttentionLinkPredictor.states``
    are symmetric for undirected graphs; E6 features are symmetric by construction.
    Modes are used for controlled ablations without test-set hyperparameter search.

    ``prior_logits`` are generated by a separately fit logistic model trained only
    on previously revealed historical-year fitting subsets. Historical prequential
    logits are cached unchanged. No model trains on final-test labels.
    """

    VALID_MODES = ('fusion', 'temporal', 'structural', 'fusion_no_recency', 'fusion_no_anchor')

    def __init__(self, input_dim: int, hidden: int = 32, heads: int = 4,
                 fusion_dim: int = 48, dropout: float = .10, mode: str = 'fusion'):
        super().__init__()
        if mode not in self.VALID_MODES:
            raise ValueError(f'Unknown mode: {mode}')
        if not 0 <= dropout < 1 or fusion_dim < 4:
            raise ValueError('Invalid network dimensions or dropout')
        self.mode = mode
        self.temporal = TemporalAttentionLinkPredictor(input_dim, hidden=hidden,
                                                        heads=heads, dropout=dropout)
        self.struct_encoder = ResidualMLP(len(FEATURE_NAMES), fusion_dim, dropout)
        self.temporal_encoder = ResidualMLP(self.temporal.state_dim, fusion_dim, dropout)
        self.feature_gate = nn.Sequential(nn.Linear(2 * fusion_dim, fusion_dim),
                                          nn.GELU(), nn.Linear(fusion_dim, fusion_dim), nn.Sigmoid())
        self.cross = nn.Sequential(
            nn.Linear(4 * fusion_dim, fusion_dim), nn.LayerNorm(fusion_dim),
            nn.GELU(), nn.Dropout(dropout), nn.Linear(fusion_dim, fusion_dim),
            nn.GELU(), nn.Dropout(dropout))
        self.residual_head = nn.Linear(fusion_dim, 1)
        self.struct_head = nn.Linear(fusion_dim, 1)
        self.temporal_head = nn.Linear(fusion_dim, 1)
        self.residual_log_scale = nn.Parameter(torch.tensor(-1.8))
        # Initialize small corrections so an already strong LR prior is respected.
        nn.init.normal_(self.residual_head.weight, std=.01)
        nn.init.zeros_(self.residual_head.bias)

    def forward(self, prepared, structural_features: torch.Tensor,
                prior_logits: torch.Tensor | None = None, ids=None,
                return_parts=False):
        """Compute logits using causal ``prepared`` and historical feature arrays.

        ``structural_features`` must contain a row for every candidate in ``prepared``.
        ``prior_logits`` are *prequential* logits, not scores from an LR model
        trained on labels for the same prediction snapshot.
        """
        if ids is None:
            ids = torch.arange(len(prepared.labels), device=prepared.x.device)
        elif not torch.is_tensor(ids):
            ids = torch.as_tensor(ids, device=prepared.x.device, dtype=torch.long)
        if structural_features.ndim != 2 or structural_features.shape != (len(prepared.labels), len(FEATURE_NAMES)):
            raise ValueError('Structural features must align with prepared candidates')
        if not torch.isfinite(structural_features).all():
            raise ValueError('Non-finite structural features')
        s = structural_features[ids]
        if self.mode == 'fusion_no_recency':
            # Remove weighted two-hop and recent-degree inputs in this ablation.
            s = torch.cat((s[:, :8], torch.zeros_like(s[:, 8:])), dim=1)
        if prior_logits is None:
            prior = torch.zeros(len(ids), device=s.device, dtype=s.dtype)
        else:
            if prior_logits.shape != (len(prepared.labels),):
                raise ValueError('Prior logits must align with all candidates')
            prior = prior_logits[ids].to(s.device)  # Preserve LR score ordering without clipping ties.

        if self.mode == 'temporal':
            t = self.temporal_encoder(self.temporal.states(prepared, ids))
            logits = self.temporal_head(t).flatten()
            return (logits, {'temporal': logits}) if return_parts else logits

        structure = self.struct_encoder(s)
        if self.mode == 'structural':
            logits = prior + torch.sigmoid(self.residual_log_scale) * self.struct_head(structure).flatten()
            return (logits, {'prior': prior, 'structural': logits - prior}) if return_parts else logits

        t = self.temporal_encoder(self.temporal.states(prepared, ids))
        gate = self.feature_gate(torch.cat((structure, t), dim=-1))
        mixed_s = (1 - gate) * structure
        mixed_t = gate * t
        interactions = torch.cat((mixed_s, mixed_t, structure * t, (structure - t).abs()), dim=-1)
        fused = self.cross(interactions)
        correction = self.residual_head(fused).flatten()
        scale = torch.sigmoid(self.residual_log_scale)
        anchor = prior if self.mode != 'fusion_no_anchor' else torch.zeros_like(prior)
        logit = anchor + scale * correction
        if return_parts:
            return logit, {'prior': anchor, 'correction': correction,
                           'scale': scale, 'gate_mean': gate.mean()}
        return logit
